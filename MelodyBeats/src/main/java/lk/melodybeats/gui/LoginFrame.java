    private void login() {

        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your username.",
                    "Username Required",
                    JOptionPane.WARNING_MESSAGE
            );

            txtUsername.requestFocus();
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your password.",
                    "Password Required",
                    JOptionPane.WARNING_MESSAGE
            );

            txtPassword.requestFocus();
            return;
        }

        String sql
                = "SELECT UserID, Username, PasswordHash, "
                + "FullName, Role "
                + "FROM USER_ACCOUNT "
                + "WHERE Username = ? AND Active = 1";

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement
                     = connection.prepareStatement(sql)) {

            statement.setString(1, username);

            try (ResultSet result = statement.executeQuery()) {

                if (!result.next()) {
                    showInvalidLogin();
                    return;
                }

                String savedPasswordHash
                        = result.getString("PasswordHash").trim();

                String enteredPasswordHash
                        = PasswordUtil.hash(password);

                if (!enteredPasswordHash.equalsIgnoreCase(
                        savedPasswordHash)) {

                    showInvalidLogin();
                    return;
                }

                int userId = result.getInt("UserID");
                String fullName = result.getString("FullName");
                String role = result.getString("Role");

                lblStatus.setForeground(
                        new java.awt.Color(0, 128, 0)
                );

                lblStatus.setText("Login successful.");

                JOptionPane.showMessageDialog(
                        this,
                        "Welcome " + fullName + "!",
                        "Login Successful",
                        JOptionPane.INFORMATION_MESSAGE
                );

                MainDashboard dashboard = new MainDashboard(
                        userId,
                        fullName,
                        role
                );
                dashboard.setVisible(true);
                dispose();
            }

        } catch (SQLException exception) {

            lblStatus.setForeground(java.awt.Color.RED);
            lblStatus.setText("Database connection failed.");

            JOptionPane.showMessageDialog(
                    this,
                    "Could not connect to MelodyBeat3.\n\n"
                    + exception.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );

            exception.printStackTrace();
        }
    }

    private void showInvalidLogin() {

        lblStatus.setForeground(java.awt.Color.RED);
        lblStatus.setText("Invalid username or password.");

        JOptionPane.showMessageDialog(
                this,
                "Invalid username or password.",
                "Login Failed",
                JOptionPane.WARNING_MESSAGE
        );

        txtPassword.setText("");
        txtPassword.requestFocus();
    }

